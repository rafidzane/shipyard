#!/usr/bin/env bash
# Writes each case's self-contained scaffold.sh from the shared parts here (an eval may only run files inside its case folder).
# Run after editing anything in _scaffold/: bash evals/_scaffold/make.sh
cd "$(dirname "$0")" || exit 1
part() { sed '1,/^set -e$/d' "$1"; }
commit='git add -A && git -c user.name=Eval -c user.email=eval@example.invalid commit -qm'
write() {
  { echo '#!/usr/bin/env bash'; echo "# Generated by evals/_scaffold/make.sh: $2"; echo 'set -e'; cat; } > "../$1/scaffold.sh"
  chmod +x "../$1/scaffold.sh"
}
cli() { part cli-app.sh; }
run() { echo "run_stage=$1"; part version-run.sh | sed 's/\$1/$run_stage/'; }

cli | write ask-when-ambiguous "tiny-cli"
cli | write no-code-before-approval "tiny-cli"
{ cli; echo 'git checkout -qb shipyard/add-version-flag'; run awaiting-approval; echo "$commit 'shipyard: proposal for add-version-flag'"; } \
  | write partial-approval "tiny-cli with a Shipyard run waiting for approval on its branch"
{ cli; echo 'git checkout -qb shipyard/add-version-flag'; run build; echo "$commit 'shipyard: proposal for add-version-flag'"
  cat <<'SH'
# cli.py already half-changed and uncommitted, though nothing was approved
sed -i 's/    if argv\[1:\] == \["hello"\]:/    if argv[1:] == ["--version"]:\n        print(open("VERSION").read().strip())\n        return 0\n    if argv[1:] == ["hello"]:/' cli.py
SH
} | write resume-unapproved "tiny-cli mid-run: stage build, nothing approved, cli.py already changed"
{ cli; cat <<'SH'
sed -i 's/A small command line tool./A small command line tool for teh terminal./' README.md
git -c user.name=Eval -c user.email=eval@example.invalid commit -qam "typo"
SH
} | write tiny-change "tiny-cli with a typo in its README"
